/** تحويل علامات ? إلى $1,$2 (مع تجاهل ما بداخل النصوص المقتبسة) */
export function toPg(sql) {
  let n = 0, out = '', quoted = false;
  for (const ch of sql) {
    if (ch === "'") quoted = !quoted;
    out += ch === '?' && !quoted ? '$' + ++n : ch;
  }
  return out;
}

const TRANSIENT = /ECONNRESET|ECONNREFUSED|ETIMEDOUT|EPIPE|Connection terminated|terminating connection|timeout exceeded when trying to connect/i;
const RETRYABLE_TX = new Set(['40P01', '40001']); // تعارض/توقف متبادل بين عمليتين: يُعاد التنفيذ
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/**
 * واجهة قاعدة البيانات: نفس أسلوب الاستدعاء القديم لكن غير متزامن.
 *   await db.get(sql, ...args)     صف واحد أو undefined
 *   await db.all(sql, ...args)     مصفوفة صفوف
 *   await db.run(sql, ...args)     { changes }
 *   await db.insert(sql, ...args)  رقم السطر الجديد (يضيف RETURNING id)
 *   await db.tx(async (t) => ...)  عملية ذرّية: استخدم t داخلها
 */
export class Db {
  constructor(target, pool, inTx = false) { this.target = target; this.pool = pool; this.inTx = inTx; }
  async query(sql, args = []) {
    try { return await this.target.query(toPg(sql), args); } catch (e) {
      if (!this.inTx && (TRANSIENT.test(String(e?.message)) || e?.code === '57P01')) {
        await sleep(400);
        return this.target.query(toPg(sql), args);
      }
      if (e && typeof e === 'object') e.sql = sql.replace(/\s+/g, ' ').slice(0, 300); // للتشخيص في السجل فقط
      throw e;
    }
  }
  async get(sql, ...args) { return (await this.query(sql, args)).rows[0]; }
  async all(sql, ...args) { return (await this.query(sql, args)).rows; }
  async run(sql, ...args) { return { changes: (await this.query(sql, args)).rowCount }; }
  async insert(sql, ...args) { return Number((await this.query(sql + ' RETURNING id', args)).rows[0].id); }
  async exec(sql) { await this.target.query(sql); }
  async tx(fn) {
    if (this.inTx) return fn(this);
    for (let attempt = 1; ; attempt++) {
      const client = await this.pool.connect();
      let broken;
      try {
        await client.query('BEGIN');
        const out = await fn(new Db(client, this.pool, true));
        await client.query('COMMIT');
        return out;
      } catch (e) {
        try { await client.query('ROLLBACK'); } catch (r) { broken = r; }
        if (TRANSIENT.test(String(e?.message))) broken = e;
        if (RETRYABLE_TX.has(e?.code) && attempt < 4) { await sleep(40 * attempt + Math.random() * 60); continue; }
        throw e;
      } finally { client.release(broken); }
    }
  }
  async close() { await this.pool.end(); }
}

export const tx = (db, fn) => db.tx(fn);

export async function getSettings(db) {
  return Object.fromEntries((await db.all('SELECT key,value FROM settings')).map((r) => [r.key, r.value]));
}

/** فتح الاتصال وتجهيز الجداول (آمن عند التكرار ومن عدة نسخ تعمل معًا) */
export async function openDb(url = process.env.DATABASE_URL, { schema } = {}) {
  if (!url) throw new Error('المتغير DATABASE_URL غير مضبوط. ضع رابط اتصال PostgreSQL (مثل رابط Neon).');
  if (schema) {
    if (!/^[a-z_][a-z0-9_]*$/.test(schema)) throw new Error('اسم المخطط غير صالح');
    const c = new pg.Client({ connectionString: url });
    await c.connect(); await c.query(`CREATE SCHEMA IF NOT EXISTS ${schema}`); await c.end();
  }
  const pool = new Pool({
    connectionString: url,
    max: Number(process.env.PG_POOL_MAX || 8),
    idleTimeoutMillis: 20_000,
    connectionTimeoutMillis: 20_000,   // يتسع لإيقاظ قاعدة Neon المجانية بعد الخمول
    keepAlive: true,
  });
  pool.on('error', (e) => console.error('اتصال قاعدة البيانات الخامل انقطع:', e.message)); // بدونه قد تتوقف العملية
  if (schema) pool.on('connect', (c) => c.query(`SET search_path TO ${schema}`));
  const db = new Db(pool, pool);
  if (schema) db.dropSchema = async () => { await pool.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`); };
  const client = await pool.connect();
  try {
    // قفل على مستوى العملية (لا الجلسة) ليعمل مع وسيط الاتصالات (pooler) في Neon ولا يتعارض بين نسختين تعملان معًا
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock(727001)');
    await client.query(SCHEMA);
    for (const [k, v] of Object.entries(DEFAULT_SETTINGS))
      await client.query('INSERT INTO settings(key,value) VALUES($1,$2) ON CONFLICT (key) DO NOTHING', [k, v]);
    // تحديث الاسم الافتراضي القديم فقط إن لم يغيّره المدير
    await client.query("UPDATE settings SET value='عالم الأسمنت ومواد البناء' WHERE key='store_name' AND value='عالم الأسمنت'");
    await client.query("UPDATE settings SET value='مستودع عالم الأسمنت ومواد البناء - مأرب' WHERE key='warehouse_name' AND value='مستودع عالم الأسمنت - مأرب'");
    await client.query('COMMIT');
  } catch (e) {
    try { await client.query('ROLLBACK'); } catch {}
    throw e;
  } finally { client.release(); }
  return db;
}
